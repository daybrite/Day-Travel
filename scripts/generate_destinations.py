#!/usr/bin/env python3
"""Generate typed city resources and capture flows from TravelBookings Cities.json."""
import json
from pathlib import Path
from download_city_photos import slug

ROOT = Path(__file__).resolve().parent.parent
rows = json.loads((ROOT / 'data/travelbookings/Cities.json').read_text())
names = json.loads((ROOT / 'data/travelbookings/city-names.json').read_text())
captions = json.loads((ROOT / 'data/travelbookings/city-captions.json').read_text())
assert set(captions) == {slug(row['name']) for row in rows}
assert all(c['source_url'].startswith('https://') and c['kind'] in {'nickname', 'description', 'designation'} for c in captions.values())
assert rows and len({row['id'] for row in rows}) == len(rows)
assert len({slug(row['name']) for row in rows}) == len(rows)
caption_doc = [
    '# City captions and sources', '',
    'Nicknames follow the user-selected [Spike’s Sight Words list](https://spikessightwords.com/100-nicknames-for-cities/) for its 21 matching destinations. Where it offers several nicknames, one is selected; existing matching captions are retained. Hong Kong uses “Pearl of the Orient”. Checked 21 November 2026.', '',
    'Tokyo, Cape Town, Bangkok, Dubai, Taipei, Istanbul, and Mexico City are absent from that list and keep their earlier sourced captions. Nicknames describe usage, not official or exclusive civic titles. The other entries distinguish factual descriptions and UNESCO designations. Translations are editorial and generated into all seven Fluent catalogs. The original imported Cities.json remains unchanged.', '',
    '| City | Caption | Type | Source |',
    '| --- | --- | --- | --- |',
]
for row in rows:
    caption = captions[slug(row['name'])]
    caption_doc.append(f'| {row["name"]} | {caption["text"]["en"]} | {caption["kind"]} | [{caption["publisher"]}]({caption["source_url"]}) |')
(ROOT / 'data/travelbookings/CAPTIONS.md').write_text('\n'.join(caption_doc) + '\n')
for locale in ['en', 'fr', 'de', 'ja', 'zh-CN', 'ko', 'ar']:
    (ROOT / f'resource/locales/{locale}/destinations.ftl').write_text(
        '# TravelBookings catalog order. Generated by scripts/generate_destinations.py.\n'
        + ''.join(f'city_{slug(row["name"])} = {names[slug(row["name"])][locale]}\n' for row in rows))
    (ROOT / f'resource/locales/{locale}/captions.ftl').write_text(
        '# Reviewed captions; sources in data/travelbookings/CAPTIONS.md. Generated.\n'
        + ''.join(f'caption_{slug(row["name"])} = {captions[slug(row["name"])]["text"][locale]}\n' for row in rows))
source = ['//! Generated by scripts/generate_destinations.py.', 'use day::prelude::*;',
          'use crate::res;', f'pub const COUNT: usize = {len(rows)};',
          'pub fn title(index: usize) -> LocalizedText {', 'match index {']
source += [f'{i} => res::str::city_{slug(row["name"])}(),' for i, row in enumerate(rows)]
source += ['_ => res::str::city_paris(),', '}}',
           'pub fn artwork(index: usize) -> day::ImageSource {', 'match index {']
for i, row in enumerate(rows):
    symbol = f'photo_{slug(row["name"])}'
    assert (ROOT / f'resource/images/{symbol}.jpg').exists(), f'Missing photo: {row["name"]}'
    source.append(f'{i} => res::images::{symbol}.into(),')
source += ['_ => res::images::photo_paris.into(),', '}}']
source += ['pub fn tagline(index: usize) -> LocalizedText { match index {']
source += [f'{i} => res::str::caption_{slug(row["name"])}(),' for i, row in enumerate(rows)]
source += ['_ => res::str::caption_paris(),', '}}']
# Provider text is retained verbatim from the user-supplied catalog, separately
# from app-owned interface messages and translated city names.
source += ['pub struct CityInfo { pub country: &\'static str, pub position: day_piece_map::LngLat }',
           'pub fn info(index: usize) -> CityInfo { match index {']
for i, row in enumerate(rows):
    source.append(f'{i} => CityInfo {{ country: {json.dumps(row["country"], ensure_ascii=False)}, position: day_piece_map::LngLat::new({row["longitude"]}, {row["latitude"]}) }},')
source += ['_ => info(0),', '}}']
(ROOT / 'src/destinations.rs').write_text('\n'.join(source) + '\n')
flow = ['# Generated: every TravelBookings destination in catalog order.',
        'flow:', '  - wait_for: { id: home_screen }']
for i, row in enumerate(rows):
    city = slug(row['name'])
    flow += [f'  - navigate: {{ route: /city-{i} }}',
             f'  - assert_text: {{ id: trip_title, key: city_{city} }}',
             '  - assert_visible: { id: destination_photo }',
             '  - wait_for: { id: city_map_ready, timeout_secs: 60 }',
             '  - assert_visible: { id: city_map }',
             '  - assert_visible: { id: ticket_picker }',
             '  - assert_visible: { id: round_trip_toggle }',
             '  - wait_idle: {}', f'  - screenshot: {city}',
             '  - nav_back: {}']
for kind in ['desktop', 'mobile']:
    capture = []
    for line in flow:
        if kind == 'mobile' and '/city-' in line:
            index = int(line.split('/city-')[1].split()[0])
            line = f'  - select: {{ id: city_list, index: {index} }}'
        elif kind == 'desktop':
            line = line.replace('nav_back: {}', 'navigate: { route: /discover }')
            line = line.replace('wait_for: { id: home_screen }', 'wait_for: { id: city_sidebar }')
        capture.append(line)
    (ROOT / f'dayscript/capture-{kind}.yaml').write_text('\n'.join(capture) + '\n')
